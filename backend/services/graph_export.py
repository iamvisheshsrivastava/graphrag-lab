"""
Export the current knowledge graph to standard interchange formats (issue #14).

Reuses the same node/edge shape already used elsewhere:
  - GraphML is produced via networkx.write_graphml on a DiGraph built from the
    same KnowledgeGraph nodes/edges GraphBuilder already produces.
  - The Cypher script mirrors the node/edge serialization persist_graph uses
    in services/neo4j_service.py (same REL_MAP), so users without Neo4j
    AuraDB access still get a loadable script with equivalent MERGE semantics.
  - JSON-LD is a lightweight semantic-web mapping of node type/properties to
    @type/@context, for interoperability with other requirements-
    traceability tooling (ISO 26262 Part 8 evidence).
"""

import io
import json
import re

import networkx as nx

from models.schemas import KnowledgeGraph
from services.neo4j_service import REL_MAP


def _flatten_properties(properties: dict) -> dict:
    """GraphML (and sane Cypher literals) need primitive attribute values —
    networkx.write_graphml raises on list/dict values (e.g. Requirement.tags)
    — so collapse anything non-primitive to its JSON string form and drop
    None values GraphML can't represent."""
    flat = {}
    for k, v in properties.items():
        if v is None:
            continue
        if isinstance(v, (list, dict)):
            flat[k] = json.dumps(v)
        else:
            flat[k] = v
    return flat


def _to_nx(graph: KnowledgeGraph) -> nx.DiGraph:
    g = nx.DiGraph()
    for node in graph.nodes:
        # node.label/node.type take precedence over any same-named key that
        # might also appear inside properties (e.g. entity nodes commonly
        # carry a redundant properties["label"]) — attrs is built flattened
        # first, then the canonical fields overwrite it.
        attrs = _flatten_properties(node.properties)
        attrs["label"] = node.label
        attrs["type"] = node.type
        g.add_node(node.id, **attrs)
    for edge in graph.edges:
        g.add_edge(edge.source, edge.target, relation=edge.relation, weight=edge.weight)
    return g


def to_graphml(graph: KnowledgeGraph) -> str:
    """Serialize to GraphML for import into Gephi/yEd."""
    g = _to_nx(graph)
    buf = io.BytesIO()
    nx.write_graphml(g, buf)
    return buf.getvalue().decode("utf-8")


def _safe_cypher_var(node_id: str) -> str:
    # Cypher variable names can't contain the characters our ids use (e.g.
    # "REQ-1"). Each MERGE below is a standalone statement and the actual
    # match is on the `id` property, so the variable name just needs to be
    # syntactically valid — it's never referenced outside its own statement.
    return "n_" + re.sub(r"[^A-Za-z0-9_]", "_", node_id)


def to_cypher(graph: KnowledgeGraph) -> str:
    """Serialize to a plain .cypher script of MERGE statements, with the same
    :Requirement/:Entity labels and relationship types persist_graph writes
    to Neo4j AuraDB."""
    lines = ["// Generated by GraphRAG Lab — GET /graph/export?format=cypher", ""]

    for node in graph.nodes:
        if node.type == "requirement":
            label = "Requirement"
            props = {
                "id": node.id,
                "label": node.label,
                "text": node.properties.get("text", ""),
                "req_type": str(node.properties.get("req_type", "")),
                "sae_level": str(node.properties.get("sae_level", "")),
                "domain": node.properties.get("domain", ""),
            }
        else:
            label = "Entity"
            props = {"id": node.id, "label": node.label, "entity_type": node.type}
        prop_str = ", ".join(f"{k}: {json.dumps(v)}" for k, v in props.items())
        lines.append(f"MERGE ({_safe_cypher_var(node.id)}:{label} {{{prop_str}}});")

    lines.append("")
    for edge in graph.edges:
        rel = REL_MAP.get(edge.relation, "RELATED_TO")
        lines.append(
            f"MATCH (a {{id: {json.dumps(edge.source)}}}), (b {{id: {json.dumps(edge.target)}}}) "
            f"MERGE (a)-[:{rel}]->(b);"
        )

    return "\n".join(lines)


def to_jsonld(graph: KnowledgeGraph) -> dict:
    """Lightweight JSON-LD export mapping node type/properties to @type."""
    context = {
        "@vocab": "https://graphrag-lab.local/ontology#",
        "id": "@id",
        "type": "@type",
        "source": {"@type": "@id"},
        "target": {"@type": "@id"},
    }

    items = []
    for node in graph.nodes:
        entry = {"@id": node.id, "@type": node.type, "label": node.label}
        entry.update(_flatten_properties(node.properties))
        items.append(entry)

    for edge in graph.edges:
        items.append({
            "@id": f"{edge.source}->{edge.target}",
            "@type": edge.relation,
            "source": edge.source,
            "target": edge.target,
            "weight": edge.weight,
        })

    return {"@context": context, "@graph": items}
